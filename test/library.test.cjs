const { test } = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs/promises")
const path = require("node:path")
const { DocumentLibrary } = require("../library.cjs")

test("recent files, pins and saved versions survive restarting the library", async () => {
  const directory = await fs.mkdtemp(path.join(__dirname, "../.build/library-test-"))
  const library = new DocumentLibrary(directory)
  await library.load()
  const id = await library.save("notes.pdf", Buffer.from("Original"))
  await library.save("notes.pdf", Buffer.from("Revised"), id)
  await library.save("second.docx", Buffer.from("Second"))
  await library.pin(id, true)
  const restored = new DocumentLibrary(directory)
  await restored.load()
  assert.equal(restored.list()[0].id, id)
  assert.equal(restored.list()[0].versionCount, 2)
  const versions = restored.versions(id)
  assert.equal((await restored.read(id, versions[1].id)).bytes.toString(), "Original")
  assert.equal((await restored.read(id)).bytes.toString(), "Revised")
  await assert.rejects(() => restored.read(id, "../unknown"), /not found/)
  await Promise.all([restored.save("notes.pdf", Buffer.from("Third"), id), restored.save("notes.pdf", Buffer.from("Fourth"), id)])
  assert.equal(restored.versions(id).length, 4)
})
