const {test}=require('node:test'),assert=require('node:assert/strict'),{chromium}=require('playwright'),{Document,Paragraph,Packer}=require('docx'),{start}=require('../server.cjs'),{clickTool,waitForAsync}=require('./menu-helper.cjs'),{strFromU8}=require('fflate'),{readWord}=require('../word.cjs')
test('Word drawing streams before pen-up, automatically joins the shared DOCX and can be undone',{timeout:60000},async()=>{
  const host=await start(),browser=await chromium.launch({channel:'msedge'})
  try{await host.open('One shared document.docx',await Packer.toBuffer(new Document({sections:[{children:[new Paragraph('Sign this document')]}]})))
    const pc=await browser.newPage(),phone=await browser.newPage({viewport:{width:390,height:844}})
    await pc.goto(host.address+'/#owner='+host.owner);await require('./menu-helper.cjs').connectPhone(pc, phone, host.address)
    await pc.locator('.word-ink-layer').waitFor({state:'attached'});await phone.locator('.word-ink-layer').waitFor({state:'attached'})
    await phone.locator('.mobile-mode-dock').getByRole('button',{name:'Draw',exact:true}).click()
    const bounds=await phone.locator('.word-ink-layer').first().boundingBox()
    await phone.mouse.move(bounds.x+bounds.width*.2,bounds.y+bounds.height*.2);await phone.mouse.down();await phone.mouse.move(bounds.x+bounds.width*.4,bounds.y+bounds.height*.25,{steps:12})
    await waitForAsync(pc,async owner=>(await(await fetch('/api/state',{headers:{Authorization:'Bearer '+owner}})).json()).preview?.kind==='word-ink',host.owner)
    // Visible-area ink tiles intentionally omit offscreen strokes. Observe the shared stroke near the page top.
    await pc.locator('#stage').evaluate(stage=>stage.scrollTop=0)
    await waitForAsync(pc,()=>{const canvas=document.querySelector('.word-ink-layer'),pixels=canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;for(let i=3;i<pixels.length;i+=4)if(pixels[i]>0)return true;return false})
    let releaseFirst,firstStarted
    const firstRequest=new Promise(resolve=>firstStarted=resolve),held=new Promise(resolve=>releaseFirst=resolve)
    let first=true
    await phone.route('**/api/word-image/**',async route=>{if(first){first=false;firstStarted();await held}await route.continue()})
    await phone.mouse.up()
    await firstRequest
    // A second stroke must autosave even when its timer overlaps the first upload.
    await phone.mouse.move(bounds.x+bounds.width*.2,bounds.y+bounds.height*.3);await phone.mouse.down();await phone.mouse.move(bounds.x+bounds.width*.4,bounds.y+bounds.height*.35,{steps:12});await phone.mouse.up()
    await new Promise(resolve=>setTimeout(resolve,400));releaseFirst()
    await pc.waitForFunction(()=>document.querySelectorAll('.word-saved-ink').length===2)
    const current=host.getDocument(),exported=await host.exportFile(current.id),parsed=await readWord(exported.bytes,'docx')
    assert.match(strFromU8(parsed.archive['word/document.xml']),/Elleson ink/)
    const phoneId=await phone.evaluate(async()=>{const token=sessionStorage.getItem('elleson-session');return (await(await fetch('/api/state',{headers:{Authorization:'Bearer '+token}})).json()).document.id});assert.equal(phoneId,current.id)
    const drawing=pc.locator('.word-saved-ink').first()
    const priorLeft=await drawing.evaluate(img=>parseFloat(img.style.left))
    await drawing.click()
    const editor=pc.locator('#word-ink-editor')
    await editor.getByLabel('Left').fill(String(Math.round((priorLeft+18)*100)/100))
    await editor.getByLabel('Size (%)').fill('120')
    await editor.getByRole('button',{name:'Apply',exact:true}).click()
    await pc.waitForFunction(prior=>Math.abs(parseFloat(document.querySelector('.word-saved-ink')?.style.left)-prior-18)<.1,priorLeft)
    await phone.waitForFunction(prior=>Math.abs(parseFloat(document.querySelector('.word-saved-ink')?.style.left)-prior-18)<.1,priorLeft)
    const moved=await readWord((await host.exportFile(current.id)).bytes,'docx')
    assert.match(strFromU8(moved.archive['word/document.xml']),new RegExp(String(Math.round((priorLeft+18)*9525))))
    await clickTool(pc,pc.locator('#history-undo'))
    await pc.waitForFunction(prior=>Math.abs(parseFloat(document.querySelector('.word-saved-ink')?.style.left)-prior)<.1,priorLeft)
    await phone.locator('.mobile-mode-dock').getByRole('button',{name:'Draw',exact:true}).click();await phone.keyboard.press('Escape')

    // Erase a saved image from its page location, then universal Undo restores it.
    await clickTool(pc,pc.locator('#word-draw'));await pc.getByText('Drawing',{exact:true}).click();await pc.locator('#drawing-eraser').check();await pc.keyboard.press('Escape')
    await pc.locator('.word-saved-ink').first().scrollIntoViewIfNeeded()
    const savedBounds=await pc.locator('.word-saved-ink').first().boundingBox()
    await pc.mouse.click(savedBounds.x+savedBounds.width/2,savedBounds.y+savedBounds.height/2)
    await pc.waitForFunction(()=>document.querySelectorAll('.word-saved-ink').length===1)
    await clickTool(pc,pc.locator('#history-undo'));await pc.waitForFunction(()=>document.querySelectorAll('.word-saved-ink').length===2)
    await phone.locator('#drawing-eraser').evaluate(n=>{n.checked=false;n.dispatchEvent(new Event('input',{bubbles:true}))})
    await clickTool(phone,phone.locator('#history-undo'))
    await pc.waitForFunction(()=>document.querySelectorAll('.word-saved-ink').length===1)
    await clickTool(phone,phone.locator('#history-undo'))
    await pc.locator('.word-saved-ink').waitFor({state:'detached'})
    assert.doesNotMatch(strFromU8((await readWord((await host.exportFile(current.id)).bytes,'docx')).archive['word/document.xml']),/Elleson ink/)
  }finally{await browser.close();await new Promise(resolve=>host.server.close(resolve))}
})
