const { test } = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs/promises")
const path = require("node:path")
const { PDFDocument } = require("pdf-lib")
const { unzipSync } = require("fflate")
const { start } = require("../server.cjs")
const { DocumentLibrary } = require("../library.cjs")

test("independent tabs retain unsaved work and reject conflicting field changes, including after restart", async () => {
  const directory = await fs.mkdtemp(path.resolve(".build/workspace-"))
  let host = await start(0, directory)
  let headers = { Authorization: "Bearer " + host.owner, "Content-Type": "application/json" }
  const state = async () => (await (await fetch(host.address + "/api/state", { headers })).json())
  const post = (url, body) => fetch(host.address + url, { method: "POST", headers, body: JSON.stringify(body) })
  try {
    const pdf = await PDFDocument.create(), page = pdf.addPage([400, 500])
    pdf.getForm().createTextField("Answer").addToPage(page, { x: 30, y: 300, width: 200, height: 30 })
    const bytes = Buffer.from(await pdf.save())
    await host.open("first.pdf", bytes)
    const first = (await state()).document
    assert.equal((await post("/api/edit/" + first.id, { id: "workspace-field-1", kind: "field", name: "Answer", before: "", value: "Unsaved first" })).status, 200)
    const conflict = await post("/api/edit/" + first.id, { id: "workspace-field-2", kind: "field", name: "Answer", before: "", value: "Conflicting answer" })
    assert.equal(conflict.status, 409); assert.equal((await conflict.json()).actual, "Unsaved first")
    await host.open("second.pdf", bytes)
    const second = (await state()).document
    assert.equal((await state()).tabs.length, 2)
    await post("/api/library/" + first.libraryId + "/open", {})
    assert.equal((await state()).document.id, first.id)
    assert.equal((await state()).document.fields.Answer, "Unsaved first")
    assert.equal((await state()).document.canUndo, true)
    await post("/api/library/" + second.libraryId + "/open", {})
    await host.server.close()
    host = await start(0, directory); headers.Authorization = "Bearer " + host.owner
    assert.equal((await state()).tabs.length, 2)
    await post("/api/library/" + first.libraryId + "/open", {})
    assert.equal((await state()).document.fields.Answer, "Unsaved first")
    const result = await host.exportFile(first.id)
    assert.equal((await PDFDocument.load(result.bytes)).getForm().getTextField("Answer").getText(), "Unsaved first")
    await post("/api/handoff", { target: "phone", page: 1, zoom: 1.5, standalone: true })
    assert.equal((await state()).handoff, null, "A handoff is only delivered to the requested device role")
  } finally { await new Promise(resolve => host.server.close(resolve)) }
})
test("version retention, deletion, backup and damaged-index recovery preserve the latest documents", async () => {
  const directory = await fs.mkdtemp(path.resolve(".build/storage-")), library = new DocumentLibrary(directory)
  await library.load(); const id = await library.save("file.pdf", Buffer.from("first"))
  await library.save("file.pdf", Buffer.from("second"), id); await library.save("file.pdf", Buffer.from("third"), id)
  await library.settings(2)
  assert.equal(library.stats().versions, 2)
  const versions = library.versions(id)
  await assert.rejects(() => library.remove(id, versions[0].id), /latest/)
  await library.remove(id, versions[1].id)
  assert.equal(library.stats().versions, 1)
  const backup = unzipSync(await library.backup())
  assert.ok(backup["index.json"]); assert.equal(Object.keys(backup).filter(name => name.startsWith("documents/")).length, 1)
  await fs.writeFile(path.join(directory, "index.json"), "damaged")
  const recovered = new DocumentLibrary(directory); await recovered.load()
  assert.ok(recovered.warning); assert.ok(recovered.list().some(record => record.id === id))
  assert.equal((await recovered.read(id)).bytes.toString(), "third")
})
