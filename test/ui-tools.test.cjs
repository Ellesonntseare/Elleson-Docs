const { clickTool, waitForAsync } = require('./menu-helper.cjs')
const { test } = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs/promises")
const { chromium } = require("playwright")
const { PDFDocument } = require("pdf-lib")
const { Document, Paragraph, Packer } = require("docx")
const { readWord } = require("../word.cjs")
const { start } = require("../server.cjs")

test("editing, review, word selection formatting and library controls work through the interface", { timeout: 90000 }, async () => {
  const host = await start(), browser = await chromium.launch({ channel: "msedge" })
  try {
    const headers = { Authorization: "Bearer " + host.owner }, state = async () => (await (await fetch(host.address + "/api/state", { headers })).json()).document
    const pdf = await PDFDocument.create(); pdf.addPage([400, 500])
    await host.open("tools.pdf", Buffer.from(await pdf.save()))
    const screen = await browser.newPage({ viewport: { width: 1220, height: 870 } }), errors = []
    screen.on("pageerror", error => errors.push(error.message))
    await screen.goto(host.address + "/#owner=" + host.owner)
    await screen.getByText("PDF ready", { exact: true }).waitFor()
    await clickTool(screen, screen.getByRole("button", { includeHidden: true, name: "Add text", exact: true }))
    await clickTool(screen, screen.locator("#ink-canvas"), { position: { x: 80, y: 135 } })
    await screen.getByLabel("Text", { exact: true }).fill("Move me")
    await clickTool(screen, screen.getByRole("dialog").getByRole("button", { includeHidden: true, name: "Add text", exact: true }))
    await screen.getByText("Change synced", { exact: true }).waitFor()
    await clickTool(screen, screen.getByRole("button", { includeHidden: true, name: "Select added content", exact: true }))
    await clickTool(screen, screen.locator("#ink-canvas"), { position: { x: 85, y: 130 } })
    await clickTool(screen, screen.getByRole("button", { includeHidden: true, name: "Edit selection", exact: true }))
    await screen.locator("#mark-x").fill("20"); await screen.locator("#mark-angle").fill("15"); await screen.locator("#mark-scale").fill("1.5")
    await clickTool(screen, screen.locator("#mark-apply"))
    await screen.locator("#mark-dialog").waitFor({ state: "hidden" })
    assert.equal((await state()).marks[0].angle, 15); assert.equal((await state()).marks[0].size, 18)
    await clickTool(screen, screen.getByRole("button", { includeHidden: true, name: "Comments & review", exact: true }))
    await screen.locator("#review-text").fill("Check signature")
    await clickTool(screen, screen.locator("#review-place"))
    await clickTool(screen, screen.locator("#ink-canvas"), { position: { x: 180, y: 200 } })
    await waitForAsync(screen, async token => (await (await fetch("/api/state", { headers: { Authorization: "Bearer " + token } })).json()).document.contentVersion === 1, host.owner)
    await clickTool(screen, screen.getByRole("button", { includeHidden: true, name: "Comments & review", exact: true }))
    await screen.locator("#review-list").getByText("Text: Check signature", { exact: true }).waitFor()
    await clickTool(screen, screen.locator("#review-dialog").getByRole("button", { includeHidden: true, name: "Close", exact: true }))
    assert.equal(await screen.locator('#tool-groups').isHidden(),true)
    await screen.keyboard.press('Escape')
    assert.equal(await screen.locator('#pdf-tools [data-mode="text"]').isHidden(),true)
    await screen.locator('summary').filter({hasText:/^PDF tools$/}).click()
    assert.equal(await screen.locator('#pdf-tools [data-mode="text"]').isVisible(),true)
    await screen.keyboard.press('Escape')
    await host.open("words.docx", await Packer.toBuffer(new Document({ sections: [{ children: [new Paragraph("Alpha beta gamma")] }] })))
    await screen.locator("#file-title").getByText("words.docx", { exact: true }).waitFor()
    await screen.locator('#word-sheet [data-word-index="0"]').waitFor()
    await clickTool(screen, screen.locator('#word-sheet [data-word-index="0"]'))
    await screen.evaluate(() => {
      const p = document.querySelector('#word-sheet [data-word-index="0"]'), walker = document.createTreeWalker(p, NodeFilter.SHOW_TEXT), text = walker.nextNode(), range = document.createRange()
      range.setStart(text, 6); range.setEnd(text, 10); getSelection().removeAllRanges(); getSelection().addRange(range); document.dispatchEvent(new Event("selectionchange"))
    })
    await clickTool(screen, screen.getByRole("button", { includeHidden: true, name: "Format paragraph", exact: true }))
    assert.equal(await screen.locator("#word-selection-only").isChecked(), true)
    await screen.locator("#word-bold").selectOption("true")
    await clickTool(screen, screen.getByRole("button", { includeHidden: true, name: "Apply formatting", exact: true }))
    await screen.locator('#word-format-dialog').waitFor({state:'hidden'})
    await screen.getByText("Change synced", { exact: true }).waitFor()
    await screen.locator('#word-sheet [contenteditable="plaintext-only"]').first().fill("Alpha beta changed")
    await screen.locator('#word-sheet [contenteditable="plaintext-only"]').first().blur()
    await waitForAsync(screen, async token => (await (await fetch("/api/state", { headers: { Authorization: "Bearer " + token } })).json()).document.lines[0].text === "Alpha beta changed", host.owner).catch(async error=>{throw Error(JSON.stringify({ui:await screen.evaluate(()=>({status:document.getElementById('status').textContent,text:document.getElementById('word-sheet').textContent,drafts:localStorage.getItem('elleson-input-drafts-v1'),pending:localStorage.getItem('elleson-pending-edits')})),server:await state()}),{cause:error})})
    const current = await state(), exported = await host.exportFile(current.id), word = await readWord(exported.bytes, "docx"), ns = word.document.documentElement.namespaceURI
    assert.equal(word.lines[0].text, 'Alpha beta changed', 'export must contain the text visible in state')
    const bold = Array.from(word.document.getElementsByTagNameNS(ns, "r")).find(run => run.getElementsByTagNameNS(ns, "b").length)
    assert.equal(bold.textContent, "beta")
    await host.markSaved(current.id, exported.changeNumber, exported)
    await clickTool(screen, screen.getByRole("button", { includeHidden: true, name: "Files", exact: true }))
    const compare = screen.locator('#library-list button:not([disabled])').filter({ hasText: /^Compare versions$/ }).first()
    await compare.click(); await clickTool(screen, screen.locator("#compare-run"))
    await screen.locator("#compare-result .changed").first().waitFor().catch(async error => {
      throw new Error(JSON.stringify(await screen.evaluate(() => ({left:document.querySelector('#compare-left').value,right:document.querySelector('#compare-right').value,options:[...document.querySelector('#compare-left').options].map(o=>({value:o.value,text:o.textContent})),result:document.querySelector('#compare-result').textContent,status:document.querySelector('#status').textContent}))),{cause:error})
    })
    await clickTool(screen, screen.locator("#compare-dialog").getByRole("button", { includeHidden: true, name: "Close", exact: true }))
    await clickTool(screen, screen.getByRole("button", { includeHidden: true, name: "Storage & backup", exact: true }))
    const promise = screen.waitForEvent("download")
    await clickTool(screen, screen.getByRole("button", { includeHidden: true, name: "Export library backup", exact: true }))
    const download = await promise; assert.ok((await fs.stat(await download.path())).size > 100)
    assert.deepEqual(errors, [])
  } finally { await browser.close(); await new Promise(resolve => host.server.close(resolve)) }
})
