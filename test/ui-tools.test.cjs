const { test } = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs/promises")
const { chromium } = require("playwright")
const { PDFDocument } = require("pdf-lib")
const { Document, Paragraph, Packer } = require("docx")
const { readWord } = require("../word.cjs")
const { start } = require("../server.cjs")

test("editing, review, word selection formatting and library controls work through the interface", { timeout: 90000 }, async () => {
  const host = await start(), browser = await chromium.launch({ channel: "msedge" })
  try {
    const headers = { Authorization: "Bearer " + host.owner }, state = async () => (await (await fetch(host.address + "/api/state", { headers })).json()).document
    const pdf = await PDFDocument.create(); pdf.addPage([400, 500])
    await host.open("tools.pdf", Buffer.from(await pdf.save()))
    const screen = await browser.newPage({ viewport: { width: 1220, height: 870 } }), errors = []
    screen.on("pageerror", error => errors.push(error.message))
    await screen.goto(host.address + "/#owner=" + host.owner)
    await screen.getByText("PDF ready", { exact: true }).waitFor()
    await screen.getByRole("button", { name: "Add text", exact: true }).click()
    await screen.locator("#ink-canvas").click({ position: { x: 80, y: 135 } })
    await screen.getByLabel("Text", { exact: true }).fill("Move me")
    await screen.getByRole("dialog").getByRole("button", { name: "Add text", exact: true }).click()
    await screen.getByText("Change synced", { exact: true }).waitFor()
    await screen.getByRole("button", { name: "Select added content", exact: true }).click()
    await screen.locator("#ink-canvas").click({ position: { x: 85, y: 130 } })
    await screen.getByRole("button", { name: "Edit selection", exact: true }).click()
    await screen.locator("#mark-x").fill("20"); await screen.locator("#mark-angle").fill("15"); await screen.locator("#mark-scale").fill("1.5")
    await screen.locator("#mark-apply").click()
    await screen.locator("#mark-dialog").waitFor({ state: "hidden" })
    assert.equal((await state()).marks[0].angle, 15); assert.equal((await state()).marks[0].size, 18)
    await screen.getByRole("button", { name: "Comments & review", exact: true }).click()
    await screen.locator("#review-text").fill("Check signature")
    await screen.locator("#review-place").click()
    await screen.locator("#ink-canvas").click({ position: { x: 180, y: 200 } })
    await screen.waitForFunction(async token => (await (await fetch("/api/state", { headers: { Authorization: "Bearer " + token } })).json()).document.contentVersion === 1, host.owner)
    await screen.getByRole("button", { name: "Comments & review", exact: true }).click()
    await screen.locator("#review-list").getByText("Text: Check signature", { exact: true }).waitFor()
    await screen.locator("#review-dialog").getByRole("button", { name: "Close", exact: true }).click()
    await screen.getByRole("button", { name: "View tools", exact: true }).click()
    assert.equal(await screen.getByRole("button", { name: "Add text", exact: true }).count(), 0)
    await screen.getByRole("button", { name: "All tools", exact: true }).click()
    await host.open("words.docx", await Packer.toBuffer(new Document({ sections: [{ children: [new Paragraph("Alpha beta gamma")] }] })))
    await screen.locator("#file-title").getByText("words.docx", { exact: true }).waitFor()
    await screen.getByRole("button", { name: "Edit text", exact: true }).click()
    await screen.locator('#word-sheet [data-word-index="0"]').waitFor()
    await screen.locator('#word-sheet [data-word-index="0"]').click()
    await screen.evaluate(() => {
      const p = document.querySelector('#word-sheet [data-word-index="0"]'), walker = document.createTreeWalker(p, NodeFilter.SHOW_TEXT), text = walker.nextNode(), range = document.createRange()
      range.setStart(text, 6); range.setEnd(text, 10); getSelection().removeAllRanges(); getSelection().addRange(range); document.dispatchEvent(new Event("selectionchange"))
    })
    await screen.getByRole("button", { name: "Format paragraph", exact: true }).click()
    assert.equal(await screen.locator("#word-selection-only").isChecked(), true)
    await screen.locator("#word-bold").selectOption("true")
    await screen.getByRole("button", { name: "Apply formatting", exact: true }).click()
    await screen.getByText("Change synced", { exact: true }).waitFor()
    await screen.locator('#word-sheet [contenteditable="plaintext-only"]').first().fill("Alpha beta changed")
    await screen.locator('#word-sheet [contenteditable="plaintext-only"]').first().blur()
    await screen.waitForFunction(async token => (await (await fetch("/api/state", { headers: { Authorization: "Bearer " + token } })).json()).document.lines[0].text === "Alpha beta changed", host.owner)
    const current = await state(), exported = await host.exportFile(current.id), word = await readWord(exported.bytes, "docx"), ns = word.document.documentElement.namespaceURI
    const bold = Array.from(word.document.getElementsByTagNameNS(ns, "r")).find(run => run.getElementsByTagNameNS(ns, "b").length)
    assert.equal(bold.textContent, "beta")
    await host.markSaved(current.id, exported.changeNumber, exported)
    await screen.getByRole("button", { name: "Files", exact: true }).click()
    const compare = screen.locator('#library-list button:not([disabled])').filter({ hasText: /^Compare versions$/ }).first()
    await compare.click(); await screen.locator("#compare-run").click()
    await screen.locator("#compare-result .changed").first().waitFor()
    await screen.locator("#compare-dialog").getByRole("button", { name: "Close", exact: true }).click()
    await screen.getByRole("button", { name: "Storage & backup", exact: true }).click()
    const promise = screen.waitForEvent("download")
    await screen.getByRole("button", { name: "Export library backup", exact: true }).click()
    const download = await promise; assert.ok((await fs.stat(await download.path())).size > 100)
    assert.deepEqual(errors, [])
  } finally { await browser.close(); await new Promise(resolve => host.server.close(resolve)) }
})
