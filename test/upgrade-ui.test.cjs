const { test } = require('node:test')
const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const { PDFDocument } = require('pdf-lib')
const { start } = require('../server.cjs')
const fs = require('node:fs/promises')

test('new documents, reading, rename, conversion and drawing Done work in the desktop interface', { timeout: 90000 }, async () => {
  const host = await start(), browser = await chromium.launch({ channel: 'msedge' })
  try {
    const screen = await browser.newPage({ viewport: { width: 1400, height: 950 } }), errors = []
    screen.on('pageerror', error => errors.push(error.message))
    await screen.goto(host.address + '/#owner=' + host.owner)
    await screen.locator('#new-document').click(); await screen.locator('#new-name').fill('My new letter')
    await screen.locator('#new-text').fill('Dear customer,\nThank you.'); await screen.locator('#new-form button.primary').click()
    await screen.locator('#file-title').filter({hasText:'My new letter.docx'}).waitFor()
    await screen.locator('#more-actions').click(); await screen.locator('#rename-document').click(); await screen.locator('#rename-name').fill('Renamed letter.docx'); await screen.locator('#rename-form button.primary').click(); await screen.locator('#more-actions').click()
    await screen.locator('#file-title').filter({hasText:'Renamed letter.docx'}).waitFor()
    const pdf = await PDFDocument.create(); pdf.addPage([400,500]); pdf.addPage([400,500])
    await host.open('Reading.pdf', Buffer.from(await pdf.save()))
    await screen.getByText('PDF ready', {exact:true}).waitFor()
    await screen.getByRole('button', {name:'Continuous reading',exact:true}).click()
    await screen.locator('.reading-page canvas').first().waitFor()
    assert.equal(await screen.locator('.reading-page').count(),2)
    await screen.getByRole('button',{name:'Exit reading',exact:true}).click()
    await screen.getByRole('button',{name:'Draw',exact:true}).click()
    const bounds = await screen.locator('#ink-canvas').boundingBox()
    await screen.mouse.move(bounds.x + 60,bounds.y + 60); await screen.mouse.down(); await screen.mouse.move(bounds.x + 150,bounds.y + 100,{steps:10}); await screen.mouse.up()
    await screen.getByRole('button',{name:'Done drawing'}).click()
    await screen.waitForFunction(() => document.getElementById('pdf-sheet').dataset.mode === 'read')
    assert.equal(host.getDocument().marks.length,1)
    await screen.locator('#convert-files').click()
    await screen.locator('#convert-input').setInputFiles({name:'notes.txt',mimeType:'text/plain',buffer:Buffer.from('Conversion fixture')})
    await screen.locator('#convert-run').click()
    await screen.locator('#convert-results').getByText(/notes - converted.pdf/).waitFor()
    assert.match(await screen.locator('#convert-progress').innerText(),/Ready to save/)
    await screen.locator('#convert-close').click()
    await fs.mkdir('.build/ui-review',{recursive:true})
    await screen.screenshot({path:'.build/ui-review/desktop.png'})
    assert.deepEqual(errors,[])
  } finally { await browser.close(); await new Promise(resolve => host.server.close(resolve)) }
})

test('phone drawing uses two fingers to navigate without leaving a stroke', { timeout:60000 }, async () => {
  const host = await start(), browser = await chromium.launch({channel:'msedge'})
  try {
    const pdf = await PDFDocument.create(); pdf.addPage([400,600]); await host.open('Touch.pdf',Buffer.from(await pdf.save()))
    const page = await browser.newPage({viewport:{width:412,height:915},hasTouch:true,isMobile:true}), cdp = await page.context().newCDPSession(page)
    await page.goto(host.address + '/#owner=' + host.owner); await page.getByText('PDF ready',{exact:true}).waitFor()
    await page.getByRole('button',{name:'Draw',exact:true}).click()
    const bounds = await page.locator('#ink-canvas').boundingBox(), x = bounds.x + bounds.width/2, y = bounds.y + 100
    const point = (id,x,y) => ({id,x,y,radiusX:4,radiusY:4,force:1})
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[point(1,x-20,y)]})
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[point(1,x-20,y),point(2,x+20,y)]})
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[point(1,x-50,y+20),point(2,x+50,y+20)]})
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
    await page.getByRole('button',{name:'Done drawing'}).click()
    assert.equal(host.getDocument().marks.length,0)
    await page.screenshot({path:'.build/ui-review/phone.png'})
  } finally { await browser.close(); await new Promise(resolve => host.server.close(resolve)) }
})
