const { _electron } = require("playwright")
const { PDFDocument } = require("pdf-lib")
const fs = require("node:fs/promises")
const path = require("node:path")
const assert = require("node:assert/strict")
const { clickTool } = require('../test/menu-helper.cjs')

async function verify() {
  const executablePath = path.resolve(process.argv[2])
  const scratch = await fs.mkdtemp(path.join(__dirname, "../.build/windows-check-"))
  const fixture = path.join(scratch, "desktop-test.pdf")
  const exported = path.join(scratch, "saved.pdf")
  const pdf = await PDFDocument.create()
  const page = pdf.addPage([400, 500])
  page.drawText("Windows application check", { x: 30, y: 450, size: 18 })
  pdf.getForm().createTextField("Name").addToPage(page, { x: 40, y: 360, width: 200, height: 24 })
  await fs.writeFile(fixture, await pdf.save())
  const application = await _electron.launch({
    executablePath, args: [fixture], timeout: 45000,
    env: { ...process.env, ELLESON_DOCS_USER_DATA: scratch, ELLESON_DOCS_TEST: "1" }
  })
  try {
    const window = await application.firstWindow()
    await window.getByText("PDF ready", { exact: true }).waitFor({ timeout: 45000 })
    assert.equal(await window.locator('#prototype-shell-style').getAttribute('media'),'all')
    await window.locator('.mobile-mode-dock').waitFor()
    const paper=window.locator('#pdf-sheet'),stage=window.locator('#stage')
    const bounds=await paper.boundingBox()
    const cursor={x:bounds.x+bounds.width*.55,y:bounds.y+bounds.height*.57}
    const base=await paper.boundingBox()
    await window.mouse.move(cursor.x,cursor.y)
    await window.keyboard.down('Control')
    for(let tick=0;tick<5;tick++)await window.mouse.wheel(0,-180)
    await window.keyboard.up('Control')
    await window.waitForFunction(width=>document.querySelector('#pdf-sheet').offsetWidth>width*1.1,base.width)
    await window.waitForFunction(()=>!document.querySelector('#stage').dataset.navigating)
    const zoomed=await paper.boundingBox()
    assert.ok(Math.abs((cursor.x-zoomed.x)/zoomed.width-.55)<.04,'horizontal zoom follows the cursor')
    assert.ok(Math.abs((cursor.y-zoomed.y)/zoomed.height-.57)<.04,'vertical zoom follows the cursor')
    const scrolled=await stage.evaluate(element=>element.scrollTop)
    await window.mouse.wheel(0,112)
    await window.waitForFunction(top=>document.querySelector('#stage').scrollTop>top,scrolled)
    assert.ok(Math.abs((await paper.boundingBox()).width-zoomed.width)<1,'plain wheel scrolls without changing zoom')
    await window.locator('.mobile-zoom-pill').getByRole('button',{name:'Fit',exact:true}).click()
    await window.waitForFunction(width=>Math.abs(document.querySelector('#pdf-sheet').offsetWidth-width)<2,base.width)
    await paper.click({button:'right',position:{x:80,y:90}})
    const menu=window.getByRole('menu',{name:'Document actions'})
    await menu.getByRole('menuitem',{name:/^Save As/}).waitFor()
    await menu.getByRole('menuitem',{name:'Find in document',exact:true}).click()
    await window.locator('#search-dialog[open]').waitFor()
    await window.keyboard.press('Escape')
    const field = window.getByRole("textbox", { name: "Name", exact: true })
    await field.fill("Native Windows save")
    await field.blur()
    await window.getByText("Change synced", { exact: true }).waitFor()
    await application.evaluate(({ dialog }, savedPath) => {
      dialog.showSaveDialog = async () => ({ canceled: false, filePath: savedPath })
    }, exported)
    await clickTool(window, window.locator("#save"))
    await window.getByText("Copy saved", { exact: true }).waitFor()
    const reopened = await PDFDocument.load(await fs.readFile(exported))
    assert.equal(reopened.getForm().getTextField("Name").getText(), "Native Windows save")
    await application.evaluate(({ dialog }, sourcePath) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [sourcePath] })
    }, exported)
    await window.locator(".mobile-file-sheet summary").click()
    await window.locator(".mobile-file-sheet").getByRole("button", {name:"Open file",exact:true}).click()
    await window.locator("#file-title").getByText("saved.pdf", { exact: true }).waitFor()
    await window.getByText("PDF ready", { exact: true }).waitFor()
    assert.equal(await window.getByRole("textbox", { name: "Name", exact: true }).inputValue(), "Native Windows save")
    await window.getByRole("textbox", { name: "Name", exact: true }).fill("Saved back to original")
    await window.getByRole("textbox", { name: "Name", exact: true }).blur()
    await window.getByText("Change synced", { exact: true }).waitFor()
    await window.locator(".mobile-file-sheet summary").click()
    await window.locator(".mobile-file-sheet").getByRole("button", {name:"Save",exact:true}).click()
    await window.waitForFunction(() => document.querySelector("#status").textContent.startsWith("Saved to "))
    assert.equal((await PDFDocument.load(await fs.readFile(exported))).getForm().getTextField("Name").getText(), "Saved back to original")
    const changed = await PDFDocument.load(await fs.readFile(exported))
    changed.getForm().getTextField("Name").setText("Changed in another application")
    await fs.writeFile(exported, await changed.save())
    await window.getByRole("textbox", { name: "Name", exact: true }).fill("Keep this edit unsaved")
    await window.getByRole("textbox", { name: "Name", exact: true }).blur()
    await window.getByText("Change synced", { exact: true }).waitFor()
    await application.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0 }) })
    await window.locator(".mobile-file-sheet summary").click()
    await window.locator(".mobile-file-sheet").getByRole("button", {name:"Save",exact:true}).click()
    await window.getByText("Save cancelled", { exact: true }).waitFor()
    assert.equal((await PDFDocument.load(await fs.readFile(exported))).getForm().getTextField("Name").getText(), "Changed in another application")
    const photoPath=path.join(scratch,'Photo.png'),photoPdf=path.join(scratch,'Photo.pdf')
    const picture=await fs.readFile(path.join(__dirname,'../web/logo.png'))
    await fs.writeFile(photoPath,picture)
    await application.evaluate(({dialog},sourcePath)=>{
      dialog.showOpenDialog=async (_window,options)=>{
        if(!options.filters[0].extensions.includes('png'))throw Error('Picture format missing from Open File')
        return {canceled:false,filePaths:[sourcePath]}
      }
    },photoPath)
    await application.evaluate(({dialog},destination)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:destination})},photoPdf)
    await window.locator('.mobile-file-sheet summary').click()
    await window.locator('.mobile-file-sheet').getByRole('button',{name:'Open file',exact:true}).click()
    await window.locator('#file-title').getByText('Photo.pdf',{exact:true}).waitFor()
    await window.getByText('PDF ready',{exact:true}).waitFor()
    await window.locator('.mobile-file-sheet summary').click()
    await window.getByRole('button',{name:'Save as PDF',exact:true}).click()
    await window.getByText('Copy saved',{exact:true}).waitFor()
    const converted=await PDFDocument.load(await fs.readFile(photoPdf))
    assert.equal(converted.getPageCount(),1)
    assert.deepEqual(await fs.readFile(photoPath),picture)
    console.log('Windows opened a PNG, exported a one-page PDF and kept the original picture intact.')
    if (process.env.ELLESON_DOCS_OUTPUTS) {
      await window.screenshot({ path: path.join(process.env.ELLESON_DOCS_OUTPUTS, "Elleson-Docs-Windows.png") })
    }
    console.log("Windows executable opened, edited, saved and reopened a PDF; normal Save updated its file and protected an external change when cancelled.")
  } finally {
    await application.close()
  }
}
verify().catch(error => { console.error(error); process.exitCode = 1 })
